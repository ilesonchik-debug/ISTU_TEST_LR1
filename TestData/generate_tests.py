    ("TA-27", "Соседние пары", [3, -3, 6, -6], [(0, 3, 1, -3), (2, 6, 3, -6)]),
    ("TA-28", "Соседние пары", [3, -3, -6], [(0, 3, 1, -3), (1, -3, 2, -6)]),
